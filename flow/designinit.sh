#!/usr/bin/env bash
# Print the .designinit that makes the INTERACTIVE EDA box (xschem, KLayout, magic, ngspice in
# the browser desktop) use the same PDK as flow.conf. The batch flow does not need it.
#   flow/designinit.sh > ~/eda/designs/.designinit      (then: docker restart eda_$USER)
set -euo pipefail
ROOT=$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)
pdk=$(sed -nE 's/^[[:space:]]*PDK[[:space:]]*\?=[[:space:]]*(.*[^[:space:]])[[:space:]]*$/\1/p' "$ROOT/flow.conf" | tail -n1)
[[ -n $pdk ]] || { echo "PDK not set in flow.conf" >&2; exit 2; }
case $pdk in
  sky130*)     scl=sky130_fd_sc_hd ;;
  gf180mcu*)   scl=gf180mcu_fd_sc_mcu7t5v0 ;;
  ihp-sg13g2*) scl=sg13g2_stdcell ;;
  *)           scl= ;;
esac
cat <<EOT
# Generated by flow/designinit.sh from flow.conf (PDK=$pdk). Read by the EDA box at startup.
export PDK=$pdk
export PDKPATH=\$PDK_ROOT/\$PDK
export STD_CELL_LIBRARY=$scl
export SPICE_USERINIT_DIR=\$PDKPATH/libs.tech/ngspice
# PDK KLayout setup first, then this project's macros (one KLayout library per project).
export KLAYOUT_PATH=\$PDKPATH/libs.tech/klayout:/foss/designs/$(basename "$ROOT")/flow/klayout
EOT
